export type Locale = "ja" | "en";
export const LOCALE_COOKIE = "disc-or-die-language";
export function isLocale(value: unknown): value is Locale { return value === "ja" || value === "en"; }

export function resolveLocale(saved?: string | null, acceptLanguage = ""): Locale {
  if (isLocale(saved)) return saved;
  const preferences = acceptLanguage.split(",").map(part => {
    const [tag, ...parameters] = part.trim().toLowerCase().split(";");
    const quality = parameters.find(value => value.trim().startsWith("q="));
    return { tag: tag.split("-")[0], q: quality ? Number(quality.trim().slice(2)) : 1 };
  }).filter(({ q }) => Number.isFinite(q) && q > 0 && q <= 1).sort((a, b) => b.q - a.q);
  const match = preferences.find(({ tag }) => isLocale(tag));
  return match && isLocale(match.tag) ? match.tag : "ja";
}

